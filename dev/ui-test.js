// 画面の自動テスト：node dev/ui-test.js（先に node dev/server.js を起動しておく）
const { chromium } = require('playwright');
const BASE = 'http://localhost:8765/';
let pass = 0, fail = 0;
const ok = (c, label) => { if (c) { pass++; console.log('  ✓ ' + label); } else { fail++; console.log('  ✗ ' + label); } };
(async () => {
  const browser = await chromium.launch({ args: ['--no-sandbox'] });
  const ctx = await browser.newContext({ viewport: { width: 375, height: 760 }, isMobile: true, hasTouch: true });
  const page = await ctx.newPage();
  const errors = [];
  page.on('pageerror', (e) => errors.push(e.message));
  page.on('dialog', (d) => d.accept());
  const go = async (h) => { await page.evaluate((x) => { location.hash = x; }, h); await page.waitForTimeout(400); };
  const count = (sel) => page.locator(sel).count();
  const text = (sel) => page.locator(sel).first().innerText();
  async function login(label, pin) {
    await go('#settings'); await page.click('[data-act="login"]');
    await page.selectOption('select[name="memberId"]', { label });
    await page.fill('input[name="pin"]', pin);
    await page.click('form[data-form="login"] button[type="submit"]'); await page.waitForTimeout(800);
  }
  async function logout() { await go('#settings'); await page.click('[data-act="logout"]'); await page.waitForTimeout(700); }

  console.log('■ 一般部員（ログインなし）');
  await page.goto(BASE); await page.waitForSelector('.board');
  ok(await count('.nav a[href="#record"]') === 0, '「記録」のタブが出ない');
  ok((await text('.board-v .num')).length > 0, 'ダッシュボードに部全体の実施回数が出る');
  await go('#record'); ok(await count('.rec-row') === 0 && await count('[data-act="login"]') === 1, '記録画面を直接開いても入力欄は出ない');
  await go('#menus'); ok(await count('[data-act="menu-new"]') === 0 && await count('.menu-card') > 0, 'メニューは見られるが、作成ボタンは出ない');
  await page.click('.menu-card'); ok(await count('[data-act="menu-edit"]') === 0, 'メニューの編集・削除ボタンは出ない'); await page.click('[data-act="sheet-close"]');
  await go('#members'); ok(await count('[data-act="member-new"]') === 0 && await count('.mlist a') >= 19, '部員一覧は見られるが、追加ボタンは出ない');
  await page.click('.mlist a'); await page.waitForTimeout(300);
  ok(await count('.mday') >= 28 && await count('[data-act="member-edit"]') === 0, '部員のカレンダーと履歴を見られる（編集ボタンは出ない）');
  await go('#rank'); ok(await count('.rrank') >= 19, 'ランキングに全選手が出る');
  const selfRate = await page.evaluate(() => Array.from(document.querySelectorAll('.rrank')).filter((li) => li.textContent.includes('自主トレ')).every((li) => li.querySelector('.rrate .dash')));
  ok(selfRate, '自主トレの部員の実施率は「－」');
  await page.click('[data-act="group"][data-v="FW"]'); ok(await count('.rrank') === 9, 'FWだけに切り替えられる');
  await page.click('[data-act="group"][data-v="BK"]'); ok(await count('.rrank') === 10, 'BKだけに切り替えられる');
  await page.click('[data-act="group"][data-v="ALL"]');
  await page.click('[data-act="sort"][data-v="rate"]'); ok((await text('.rrank .rrate')).includes('%'), '実施率順に切り替えられる');
  await page.click('[data-act="kind"][data-v="month"]'); ok((await text('.plabel')).includes('2026年11月'), '月間に切り替えられる');
  await page.click('[data-act="period"][data-v="-1"]'); await page.waitForTimeout(500); ok((await text('.plabel')).includes('2026年10月'), '前の月に移動できる');
  await page.click('[data-act="period"][data-v="1"]'); await page.click('[data-act="kind"][data-v="week"]');
  await go('#cal'); ok(await count('.matrix tbody tr') === 19 && await count('.matrix thead th') === 9, '週間の一覧カレンダー（19人×7日）');
  ok(await count('.cell.s-done') > 0 && await count('.cell .sr') > 0, 'マス目は色だけでなく記号と読み上げ用の文字を持つ');
  await go('#logs'); ok(await count('.logs li') === 0, '操作履歴は見られない');

  console.log('■ マネージャー');
  await login('マネ 花子（マネージャー）', 'test-mgr-01');
  ok(await count('.nav a[href="#record"]') === 1, '「記録」のタブが出る');
  await go('#record');
  const rows = await count('.rec-row');
  ok(rows === 19, '選手19人全員が記録の対象として並ぶ（自主トレの人も含む）');
  ok(await page.evaluate(() => Array.from(document.querySelectorAll('.rec-row:not(.locked)')).every((r) => r.querySelectorAll('.rec-b button').length === 2)), '選択肢は「実施した」「していない」の2つだけ');
  ok(await count('.rec-row.locked') >= 1, 'ほかのマネージャーが入力した記録は鍵つきで変更できない');
  const before = await count('.rec-row.st-none');
  await page.locator('.rec-row.st-none button[data-v="done"]').first().click();
  ok(await count('.rec-row.st-none') === before - 1 && await count('.rec-row.changed') === 1, 'ワンタップで「実施した」になる');
  await page.locator('.rec-row.changed button[data-v="done"]').first().click();
  ok(await count('.rec-row.changed') === 0, '同じボタンをもう一度押すと未記録に戻る');
  await page.click('[data-act="rec-all"]'); await page.waitForTimeout(200);
  ok(await count('.rec-row.st-none') === 0, 'まとめて「実施した」にできる');
  await page.locator('.rec-row.changed button[data-v="not"]').first().click();
  ok(await count('.rec-row.st-not.changed') === 1, 'まとめたあとで個別に「していない」へ変えられる');
  await page.click('[data-act="rec-confirm"]');
  ok((await text('.confirm')).includes('新しく記録する（' + before + '人）'), '保存前に内容を確認できる');
  await page.click('[data-act="rec-save"]'); await page.waitForTimeout(900);
  ok(await count('.rec-row.changed') === 0 && await count('.rec-row.st-none') === 0, '保存できる');
  await page.locator('.rec-row.st-not:not(.locked) button[data-v="done"]').first().click();
  await page.click('[data-act="rec-confirm"]'); ok((await text('.confirm')).includes('修正する（1人）'), '保存後に修正できる（確認画面に「修正」と出る）');
  await page.click('[data-act="rec-save"]'); await page.waitForTimeout(900);
  await page.reload(); await page.waitForSelector('.rec-row');
  ok(await count('.rec-row.st-none') === 0 && await count('.rec-row.st-not') === 0, '再読み込みしても保存した内容が残っている');
  ok(await page.locator('[data-act="rec-day"][data-v="1"]').isDisabled(), '未来の日付には進めない');
  await page.click('[data-act="rec-day"][data-v="-1"]'); await page.click('[data-act="rec-day"][data-v="-1"]'); await page.waitForTimeout(300);
  ok((await text('.rec-pick span')).includes('11/11'), '過去の日付（11/11）に移動できる');
  ok((await text('.rec-menus')).includes('ありません') && await count('.rec-row') === 19, 'メニューが無い日でも全員を記録できる');
  await page.locator('.rec-row.st-none button[data-v="done"]').first().click();
  await page.click('[data-act="rec-confirm"]'); await page.click('[data-act="rec-save"]'); await page.waitForTimeout(900);
  ok(await count('.rec-row.changed') === 0, '過去の日付の記録を保存できる');
  await go('#menus'); ok(await count('[data-act="menu-new"]') === 0, 'メニューの作成ボタンは出ない');
  await go('#members'); ok(await count('[data-act="member-new"]') === 0, '部員の追加ボタンは出ない');
  await logout();

  console.log('■ FWリーダー');
  await login('前田 剛（FWリーダー）', 'test-lead-1');
  ok(await count('.nav a[href="#record"]') === 0, '「記録」のタブが出ない');
  await go('#record'); ok(await count('.rec-row') === 0, '記録画面を開いても入力できない');
  await go('#menus'); await page.click('[data-act="menu-new"]');
  ok((await text('#tgt-hint')).includes('6人'), '対象人数の目安が出る（FWのメニュー参加者6人）');
  await page.click('.radios input[value="ALL"]', { force: true }); await page.waitForTimeout(100);
  ok((await text('#tgt-hint')).includes('13人'), '全体にすると対象は13人（自主トレ6人は入らない）');
  await page.fill('input[name="title"]', '画面テスト'); await page.fill('textarea[name="content"]', 'プランク');
  await page.click('form[data-form="menu"] button[type="submit"]'); await page.waitForTimeout(900);
  ok((await text('.menus')).includes('画面テスト'), 'メニューを登録できる');
  await page.locator('.menu-card', { hasText: '画面テスト' }).click(); await page.click('[data-act="menu-edit"]');
  await page.fill('input[name="title"]', '画面テスト改'); await page.click('form[data-form="menu"] button[type="submit"]'); await page.waitForTimeout(900);
  ok((await text('.menus')).includes('画面テスト改'), 'メニューを編集できる');
  await page.locator('.menu-card', { hasText: '画面テスト改' }).click(); await page.click('[data-act="menu-del"]'); await page.waitForTimeout(900);
  ok(!(await text('.main')).includes('画面テスト改'), 'メニューを削除できる');
  await logout();

  console.log('■ 管理者');
  await login('管理 太郎（管理者）', 'test-admin-1');
  await go('#members'); await page.click('[data-act="member-new"]');
  await page.fill('input[name="name"]', '新人 一年'); await page.click('.radios input[name="group"][value="BK"]', { force: true });
  await page.click('form[data-form="member"] button[type="submit"]'); await page.waitForTimeout(900);
  ok((await text('.main')).includes('新人 一年'), '部員を追加できる');
  await page.locator('.mlist a', { hasText: '新人 一年' }).click(); await page.waitForTimeout(300);
  await page.click('[data-act="member-edit"]'); await page.click('.radios input[name="mode"][value="leader"]', { force: true });
  await page.click('form[data-form="member"] button[type="submit"]'); await page.waitForTimeout(900);
  ok((await text('.sub-h')).includes('メニュー参加'), '取り組み方を「メニュー参加」に変更できる');
  await page.click('[data-act="member-edit"]'); await page.selectOption('select[name="role"]', 'manager');
  await page.click('form[data-form="member"] button[type="submit"]'); await page.waitForTimeout(900);
  ok((await text('.sub-h')).includes('マネージャー'), '権限を変更できる');
  await page.click('[data-act="member-edit"]'); await page.click('[data-act="pin-reset"]'); await page.waitForTimeout(900);
  ok(/^\d{6}$/.test((await text('.pin')).trim()), '暗証番号を発行できる（6桁が一度だけ表示される）');
  await page.click('[data-act="sheet-close"]');
  await page.click('[data-act="member-edit"]'); await page.click('[data-act="member-del"]'); await page.waitForTimeout(1000);
  ok((await text('.main')).includes('削除した部員'), '部員を削除できる（削除した部員の欄に移る）');
  await go('#record'); ok(await count('.rec-row.locked') === 0 && await count('.rec-row') >= 19, '管理者はだれの記録でも修正できる（鍵が付かない）');
  await go('#logs'); await page.waitForTimeout(800); ok(await count('.logs li') > 10, '操作履歴を見られる');
  ok((await text('.logs')).includes('記録を修正') && (await text('.logs')).includes('部員を削除'), '記録の修正・部員の削除が履歴に残っている');
  await page.setViewportSize({ width: 320, height: 640 }); await go('#record');
  const w = await page.evaluate(() => [document.documentElement.scrollWidth, document.documentElement.clientWidth]);
  ok(w[0] <= w[1] + 1, '幅320pxの小さいスマホでも横にはみ出さない');

  ok(errors.length === 0, '画面のエラーなし' + (errors.length ? ': ' + errors.join(' / ') : ''));
  console.log('\n合格 ' + pass + ' / 不合格 ' + fail);
  await browser.close();
  process.exit(fail ? 1 : 0);
})().catch((e) => { console.error(e); process.exit(1); });
